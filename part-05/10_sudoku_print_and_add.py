def print_sudoku(sudoku: list):
    for i in range(len(sudoku)):
        row = sudoku[i]
        if i > 0 and i % 3 == 0:
            print()
        for j in range(len(row)):
            if j > 0 and j % 3 == 0:
                print(" ", end="")
            if row[j] == 0:
                print("_", end=" ")
            else:
                print(row[j], end=" ")
        print()


def add_number(sudoku: list, row_no: int, column_no: int, number:int):
    sudoku[row_no][column_no] = number


